"""Extract artifact metrics from results/ensemble.json into LaTeX macros.

ZERO manual numbers in report/main.tex: every metric is injected through the
macros generated here. Pre-run artifacts (status "planned" or "running")
render an explicit [PENDING SWEEP] placeholder instead of any value.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

PENDING = r"\texttt{[PENDING SWEEP]}"
DEFAULT_ARTIFACT = Path("results/ensemble.json")
DEFAULT_OUTPUT = Path("report/generated_metrics.tex")


def _fmt_pct(value: float | None) -> str:
    return f"{value:.2f}\\%" if value is not None else PENDING


def _fmt_float(value: float | None, digits: int = 2) -> str:
    return f"{value:.{digits}f}" if value is not None else PENDING


def generate_latex_macros(artifact_path: Path, out_tex_path: Path) -> None:
    data = json.loads(Path(artifact_path).read_text(encoding="utf-8"))
    meta = data["meta"]
    status = meta["status"]

    lines = [
        "% AUTO-GENERATED BY render_tex_macros.py - ZERO MANUAL NUMBERS",
        f"\\newcommand{{\\ArtifactStatus}}{{{status.upper()}}}",
        f"\\newcommand{{\\ArtifactGitSHA}}{{{meta['git_sha'][:8]}}}",
        f"\\newcommand{{\\EvalSeedCount}}{{{len(meta['evaluation_seeds'])}}}",
    ]

    if status in ("planned", "running"):
        lines.extend(
            [
                f"\\newcommand{{\\MetricNRMSEBaseline}}{{{PENDING}}}",
                f"\\newcommand{{\\MetricNRMSESmith}}{{{PENDING}}}",
                f"\\newcommand{{\\MetricTNDBaseline}}{{{PENDING}}}",
                f"\\newcommand{{\\MetricTNDSmith}}{{{PENDING}}}",
                f"\\newcommand{{\\MetricHLDiff}}{{{PENDING}}}",
                f"\\newcommand{{\\MetricCliffsDelta}}{{{PENDING}}}",
                f"\\newcommand{{\\MetricHolmP}}{{{PENDING}}}",
            ]
        )
    else:
        by_variant = {row["variant"]: row for row in data["summary_table"]}
        baseline = by_variant.get("unfiltered_pi", data["summary_table"][0])
        proposed = by_variant.get("gated_akf_smith", data["summary_table"][-1])
        comp = data["ablation_comparisons"][0]
        lines.extend(
            [
                f"\\newcommand{{\\MetricNRMSEBaseline}}{{{_fmt_pct(baseline['nrmse_median_pct'])}}}",
                f"\\newcommand{{\\MetricNRMSESmith}}{{{_fmt_pct(proposed['nrmse_median_pct'])}}}",
                f"\\newcommand{{\\MetricTNDBaseline}}{{{_fmt_float(baseline['tnd_median_veh_h'])}}}",
                f"\\newcommand{{\\MetricTNDSmith}}{{{_fmt_float(proposed['tnd_median_veh_h'])}}}",
                f"\\newcommand{{\\MetricHLDiff}}{{{_fmt_float(comp['hl_median_diff'])}}}",
                f"\\newcommand{{\\MetricCliffsDelta}}{{{_fmt_float(comp['cliffs_delta'])}}}",
                f"\\newcommand{{\\MetricHolmP}}{{{_fmt_float(comp['p_value_holm'], 4)}}}",
            ]
        )

    out_path = Path(out_tex_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    artifact = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_ARTIFACT
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUTPUT
    generate_latex_macros(artifact, output)
    print(f"LaTeX macros written to {output}")
